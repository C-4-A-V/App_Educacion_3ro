package com.example.mpazpro.backend;

import java.nio.file.Path;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;
import static org.junit.jupiter.api.Assertions.*;

class ActualizacionAulaPersistenteTest {
    @TempDir Path temporal;

    @Test
    void conservaDatosDeLaBaseAnteriorAlAgregarPublicaciones() throws Exception {
        String ruta = temporal.resolve("base-anterior").toAbsolutePath().toString().replace('\\', '/');
        String jdbc = "jdbc:h2:file:" + ruta;
        try (var conexion = DriverManager.getConnection(jdbc, "sa", "");
             var sql = conexion.createStatement()) {
            sql.execute("CREATE TABLE identidad_catalogo (id BIGINT PRIMARY KEY, identificador VARCHAR(36) NOT NULL UNIQUE)");
            sql.execute("INSERT INTO identidad_catalogo VALUES (1, '11111111-1111-1111-1111-111111111111')");
            sql.execute("CREATE TABLE cursos_compartidos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, seccion VARCHAR(1) NOT NULL UNIQUE)");
            sql.execute("INSERT INTO cursos_compartidos (id,seccion) VALUES (1,'A'), (2,'B')");
            sql.execute("CREATE TABLE actividades (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asignatura_id VARCHAR(255), titulo VARCHAR(255), pregunta VARCHAR(255))");
            sql.execute("INSERT INTO actividades (id,asignatura_id,titulo,pregunta) VALUES (1,'lenguaje','Prueba anterior','Una pregunta')");
        }
        try (var contexto = new SpringApplicationBuilder(MpazBackendApplication.class)
                .web(WebApplicationType.NONE)
                .run("--spring.datasource.url=" + jdbc, "--spring.jpa.hibernate.ddl-auto=update",
                     "--spring.profiles.active=aula-local", "--spring.main.banner-mode=off")) {
            assertEquals("11111111-1111-1111-1111-111111111111",
                contexto.getBean(IdentidadCatalogoRepository.class).findById(1L).orElseThrow().getIdentificador());
            assertEquals(2, contexto.getBean(CursoCompartidoRepository.class).count());
            assertEquals("Prueba anterior", contexto.getBean(ActividadRepository.class).findById(1L).orElseThrow().getTitulo());
            assertEquals(0, contexto.getBean(PublicacionActividadRepository.class).count());
        }
    }
}
